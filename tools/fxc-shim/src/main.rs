//! Minimal stand-in for the Windows SDK's fxc.exe, covering what GPUI's build script uses:
//!   fxc /T <target> /E <entry> /Fh <header.h> /Vn <var> [/O3] <file.hlsl>
//! It calls D3DCompile from d3dcompiler_47.dll (part of Windows) and writes the same C header fxc does.
use std::ffi::{c_void, CString};
use std::os::windows::ffi::OsStrExt;

#[repr(C)]
struct BlobVtbl {
    _qi: usize,
    _add_ref: usize,
    release: unsafe extern "system" fn(*mut Blob) -> u32,
    get_buffer_pointer: unsafe extern "system" fn(*mut Blob) -> *mut c_void,
    get_buffer_size: unsafe extern "system" fn(*mut Blob) -> usize,
}
#[repr(C)]
struct Blob {
    vtbl: *const BlobVtbl,
}
type D3DCompile = unsafe extern "system" fn(
    *const c_void, usize, *const i8, *const c_void, *mut c_void, *const i8, *const i8, u32, u32, *mut *mut Blob, *mut *mut Blob,
) -> i32;

extern "system" {
    fn LoadLibraryW(name: *const u16) -> *mut c_void;
    fn GetProcAddress(module: *mut c_void, name: *const i8) -> *mut c_void;
}

unsafe fn bytes(b: *mut Blob) -> Vec<u8> {
    let v = &*(*b).vtbl;
    std::slice::from_raw_parts((v.get_buffer_pointer)(b) as *const u8, (v.get_buffer_size)(b)).to_vec()
}

fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let (mut target, mut entry, mut header, mut var, mut file, mut opt3) = (None, None, None, None, None, false);
    let mut i = 0;
    while i < args.len() {
        let a = args[i].to_ascii_lowercase().replace('-', "/");
        let mut next = || { i += 1; args.get(i).cloned() };
        match a.as_str() {
            "/t" => target = next(),
            "/e" => entry = next(),
            "/fh" => header = next(),
            "/vn" => var = next(),
            "/o3" => opt3 = true,
            "/nologo" => {}
            _ => file = Some(args[i].clone()),
        }
        i += 1;
    }
    let (Some(target), Some(entry), Some(header), Some(file)) = (target, entry, header, file) else {
        eprintln!("usage: fxc /T target /E entry /Fh out.h /Vn name [/O3] file.hlsl");
        std::process::exit(2);
    };
    let var = var.unwrap_or_else(|| format!("g_{entry}"));
    let src = std::fs::read(&file).unwrap_or_else(|e| { eprintln!("{file}: {e}"); std::process::exit(1) });
    unsafe {
        let dll: Vec<u16> = std::ffi::OsStr::new("d3dcompiler_47.dll").encode_wide().chain([0]).collect();
        let module = LoadLibraryW(dll.as_ptr());
        if module.is_null() { eprintln!("d3dcompiler_47.dll not found"); std::process::exit(1) }
        let f = GetProcAddress(module, b"D3DCompile\0".as_ptr() as *const i8);
        if f.is_null() { eprintln!("D3DCompile not found"); std::process::exit(1) }
        let compile: D3DCompile = std::mem::transmute(f);
        let (name, entry_c, target_c) = (CString::new(file.clone()).unwrap(), CString::new(entry.clone()).unwrap(), CString::new(target.clone()).unwrap());
        let flags = if opt3 { 1 << 15 } else { 0 }; // D3DCOMPILE_OPTIMIZATION_LEVEL3
        let (mut code, mut errors): (*mut Blob, *mut Blob) = (std::ptr::null_mut(), std::ptr::null_mut());
        // (ID3DInclude*)1 = D3D_COMPILE_STANDARD_FILE_INCLUDE: #include relative to the file.
        let hr = compile(src.as_ptr() as _, src.len(), name.as_ptr(), std::ptr::null(), 1 as *mut c_void, entry_c.as_ptr(), target_c.as_ptr(), flags, 0, &mut code, &mut errors);
        if !errors.is_null() {
            eprint!("{}", String::from_utf8_lossy(&bytes(errors)));
            ((*(*errors).vtbl).release)(errors);
        }
        if hr < 0 || code.is_null() {
            eprintln!("compilation failed (0x{:08x})", hr as u32);
            std::process::exit(1);
        }
        let data = bytes(code);
        ((*(*code).vtbl).release)(code);
        let mut out = format!("// Generated by fxc stand-in (d3dcompiler_47.dll)\n// {target} {entry}\n\nconst BYTE {var}[] =\n{{\n");
        for (n, chunk) in data.chunks(6).enumerate() {
            let line: Vec<String> = chunk.iter().map(|b| format!("{b:3}")).collect();
            out.push_str("    ");
            out.push_str(&line.join(", "));
            out.push_str(if (n + 1) * 6 < data.len() { ",\n" } else { "\n" });
        }
        out.push_str("};\n");
        std::fs::write(&header, out).unwrap_or_else(|e| { eprintln!("{header}: {e}"); std::process::exit(1) });
    }
}
